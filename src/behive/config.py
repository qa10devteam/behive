# ─── Config Management ────────────────────────────────────────────────────────

def load_config() -> dict:
    """Load config from ~/.behive/config.yaml or return defaults."""
    if CONFIG_FILE.exists():
        try:
            import yaml
            with open(CONFIG_FILE) as f:
                cfg = yaml.safe_load(f) or {}
            return cfg
        except ImportError:
            # Fallback: simple key=value parsing
            cfg = {}
            for line in CONFIG_FILE.read_text().splitlines():
                line = line.strip()
                if line and not line.startswith("#") and ":" in line:
                    k, v = line.split(":", 1)
                    cfg[k.strip()] = v.strip()
            return cfg
    return {}


def save_config(cfg: dict):
    """Save config to ~/.behive/config.yaml."""
    CONFIG_DIR.mkdir(parents=True, exist_ok=True)
    try:
        import yaml
        with open(CONFIG_FILE, "w") as f:
            yaml.dump(cfg, f, default_flow_style=False, sort_keys=False)
    except ImportError:
        # Fallback: manual YAML-like format
        lines = ["# BeHive Configuration\n", "# Generated by: behive config\n\n"]
        for k, v in cfg.items():
            if isinstance(v, dict):
                lines.append(f"{k}:\n")
                for sk, sv in v.items():
                    lines.append(f"  {sk}: {sv}\n")
            else:
                lines.append(f"{k}: {v}\n")
        CONFIG_FILE.write_text("".join(lines))


def get_model_for_stage(stage: str) -> str:
    """Get the configured model for a pipeline stage.
    
    Priority (highest wins):
    1. BEHIVE_MODEL_{STAGE} env var
    2. BEHIVE_MODEL env var (global)
    3. config.yaml stage-specific
    4. config.yaml default
    5. hardcoded default
    """
    # Env var per-stage (highest priority — useful for Docker/CI overrides)
    env_stage = os.environ.get(f"BEHIVE_MODEL_{stage.upper()}")
    if env_stage:
        return MODEL_PRESETS.get(env_stage, env_stage)
    
    # Env var global
    env_global = os.environ.get("BEHIVE_MODEL")
    if env_global:
        return MODEL_PRESETS.get(env_global, env_global)
    
    # Config file
    cfg = load_config()
    models = cfg.get("models", {})
    
    # Stage-specific from config
    model_name = models.get(stage)
    if model_name:
        return MODEL_PRESETS.get(model_name, model_name)
    
    # Global from config
    model_name = models.get("default")
    if model_name:
        return MODEL_PRESETS.get(model_name, model_name)
    
    # Hardcoded default
    model_name = STAGES[stage]["default"]
    return MODEL_PRESETS.get(model_name, model_name)


def get_all_stage_models() -> dict:
    """Get model assignments for all stages."""
    return {stage: get_model_for_stage(stage) for stage in STAGES}


