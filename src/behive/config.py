def run_quick_config():
    """Quick config — one model for everything."""
    print("\n🐝 BeHive Quick Config")
    print("=" * 50)
    print("\nChoose a model for all pipeline stages:\n")
    
    presets = list(MODEL_PRESETS.keys())
    for i, name in enumerate(presets, 1):
        marker = "⭐" if name == "claude-haiku" else "  "
        print(f"  {marker} {i:2d}. {name:20s} → {MODEL_PRESETS[name]}")
    
    print(f"\n  Or type any litellm-compatible model string (e.g. 'ollama/mistral')")
    print(f"\n  Recommended combos:")
    for name, combo in RECOMMENDED_COMBOS.items():
        print(f"    [{name}] {combo['description']}")
    
    choice = input(f"\nModel or combo name [balanced]: ").strip() or "balanced"
    
    if choice in RECOMMENDED_COMBOS:
        combo = RECOMMENDED_COMBOS[choice]
        cfg = load_config()
        cfg["models"] = {stage: combo[stage] for stage in STAGES}
        save_config(cfg)
        print(f"\n✅ Applied '{choice}' preset:")
        for stage in STAGES:
            resolved = MODEL_PRESETS.get(combo[stage], combo[stage])
            print(f"   {stage:10s} → {resolved}")
    elif choice.isdigit() and 1 <= int(choice) <= len(presets):
        model_name = presets[int(choice) - 1]
        cfg = load_config()
        cfg["models"] = {"default": model_name}
        save_config(cfg)
        resolved = MODEL_PRESETS.get(model_name, model_name)
        print(f"\n✅ All stages → {resolved}")
    else:
        # Treat as model string or preset name
        model_name = choice
        cfg = load_config()
        cfg["models"] = {"default": model_name}
        save_config(cfg)
        resolved = MODEL_PRESETS.get(model_name, model_name)
        print(f"\n✅ All stages → {resolved}")
    
    print(f"\n   Config saved: {CONFIG_FILE}")
    print(f"   Run 'behive config --show' to verify.\n")


def run_full_config():
    """Full config — pick model per stage."""
    print("\n🐝 BeHive Full Config — Model per Stage")
    print("=" * 50)
    print("\nPipeline stages (data flows top to bottom):\n")
    
    for stage, info in STAGES.items():
        print(f"  [{stage:8s}] {info['description']}")
        print(f"             {info['role']}")
        print()
    
    print("Available models:")
    presets = list(MODEL_PRESETS.keys())
    for i, name in enumerate(presets, 1):
        print(f"  {i:2d}. {name:20s} → {MODEL_PRESETS[name]}")
    
    print(f"\n  Or type any litellm model string. Press Enter for default.\n")
    
    cfg = load_config()
    models = {}
    
    for stage, info in STAGES.items():
        default = info["default"]
        choice = input(f"  {stage:8s} [{default}]: ").strip()
        
        if not choice:
            models[stage] = default
        elif choice.isdigit() and 1 <= int(choice) <= len(presets):
            models[stage] = presets[int(choice) - 1]
        else:
            models[stage] = choice
    
    cfg["models"] = models
    save_config(cfg)
    
    print(f"\n✅ Config saved:")
    for stage, model in models.items():
        resolved = MODEL_PRESETS.get(model, model)
        print(f"   {stage:10s} → {resolved}")
    print(f"\n   File: {CONFIG_FILE}")
    print(f"   Run 'behive config --show' to verify.\n")


def show_config():
    """Show current configuration."""
    print("\n🐝 BeHive Current Config")
    print("=" * 50)
    
    if not CONFIG_FILE.exists():
        print(f"\n  No config file found ({CONFIG_FILE})")
        print(f"  Using defaults. Run 'behive config --quick' to set up.\n")
    else:
        print(f"\n  Config: {CONFIG_FILE}\n")
    
    print("  Stage        Model                                      Source")
    print("  " + "─" * 70)
    
    cfg = load_config()
    models = cfg.get("models", {})
    
    for stage in STAGES:
        resolved = get_model_for_stage(stage)
        
        # Determine source
        if stage in models:
            source = "config (stage)"
        elif "default" in models:
            source = "config (global)"
        elif os.environ.get(f"BEHIVE_MODEL_{stage.upper()}"):
            source = "env var"
        elif os.environ.get("BEHIVE_MODEL"):
            source = "env var (global)"
        else:
            source = "default"
        
        print(f"  {stage:10s}   {resolved:42s} {source}")
    
    # Also show env vars if set
    env_models = {k: v for k, v in os.environ.items() if k.startswith("BEHIVE_MODEL")}
    if env_models:
        print(f"\n  Environment overrides:")
        for k, v in env_models.items():
            print(f"    {k}={v}")
    
    print()
